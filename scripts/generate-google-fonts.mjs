#!/usr/bin/env node
/**
 * Regenerates `src/features/avatarDecorations/googleFonts.ts` from Google's
 * public font metadata.
 *
 * The catalog holds family names and categories only: no font files and no
 * gstatic URLs. Faces are fetched at runtime by `nameFonts.ts`, because a name
 * can use any of ~1800 families and shipping them all is not an option.
 *
 *   node scripts/generate-google-fonts.mjs [--refresh]
 *
 * `--refresh` bypasses the cached metadata download; otherwise the script is
 * offline-friendly after the first run.
 */

import {mkdir, readFile, writeFile} from 'node:fs/promises'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'

const METADATA_URL = 'https://fonts.google.com/metadata/fonts'
const here = dirname(fileURLToPath(import.meta.url))
const cacheFile = join(here, '.cache', 'google-fonts.json')
const outFile = join(
  here,
  '..',
  'src',
  'features',
  'avatarDecorations',
  'googleFonts.ts',
)

/** Categories Google uses, in the order the picker shows them. */
const CATEGORIES = ['Sans Serif', 'Display', 'Serif', 'Handwriting', 'Monospace']

/** Families that hold glyphs other than letters, so a name would render tofu. */
const NOT_TEXT = /\b(Symbols|Emoji|Math|Music)\b/i

async function readMetadata(refresh) {
  if (!refresh) {
    try {
      return JSON.parse(await readFile(cacheFile, 'utf8'))
    } catch {}
  }
  const res = await fetch(METADATA_URL, {
    headers: {'user-agent': 'Mozilla/5.0'},
  })
  if (!res.ok) throw new Error(`fonts metadata failed: ${res.status}`)
  const text = await res.text()
  // The endpoint prefixes its JSON with `)]}'` to defuse script tags.
  const json = JSON.parse(text.replace(/^\)\]\}'\s*/, ''))
  await mkdir(dirname(cacheFile), {recursive: true})
  await writeFile(cacheFile, JSON.stringify(json))
  return json
}

function select(families) {
  return families
    .filter(
      family =>
        family.subsets?.includes('latin') &&
        family.fonts?.['400'] &&
        family.category &&
        CATEGORIES.includes(family.category) &&
        !NOT_TEXT.test(family.family),
    )
    .sort(
      (a, b) =>
        (a.popularity ?? Infinity) - (b.popularity ?? Infinity) ||
        a.family.localeCompare(b.family),
    )
    .map(family => [family.family, CATEGORIES.indexOf(family.category)])
}

const json = await readMetadata(process.argv.includes('--refresh'))
const rows = select(json.familyMetadataList)

/*
 * `nameFonts.ts` slugs a family into the alias its face registers under. Two
 * families that slug the same would hand a name someone else's face, so fail
 * here instead of shipping it.
 */
const aliases = new Map()
for (const [family] of rows) {
  const alias = family.toLowerCase().replace(/[^a-z0-9]+/g, '_')
  const clash = aliases.get(alias)
  if (clash) throw new Error(`font alias ${alias} collides: ${clash} / ${family}`)
  aliases.set(alias, family)
}

const data = rows.map(([family, category]) => `${family}\t${category}`).join('\n')

const source = `/**
 * Google Fonts families a display name can use.
 *
 * Generated by \`scripts/generate-google-fonts.mjs\`; do not edit by hand. Only
 * families that ship latin glyphs and an upright regular face are listed, in
 * Google's popularity order. Files are fetched at runtime by \`nameFonts.ts\`.
 */
export const GOOGLE_FONT_CATEGORIES = [
${CATEGORIES.map(category => `  '${category}',`).join('\n')}
] as const

export type GoogleFontCategory = (typeof GOOGLE_FONT_CATEGORIES)[number]

export type GoogleFont = {
  family: string
  category: GoogleFontCategory
}

/** One line per family: tab-separated family and category index. */
const DATA = \`
${data}
\`

let catalog: GoogleFont[] | undefined
let byFamily: Map<string, GoogleFont> | undefined

function loadCatalog() {
  if (!catalog) {
    catalog = DATA.trim()
      .split('\\n')
      .map(line => {
        const [family, category] = line.split('\\t')
        return {
          family,
          category: GOOGLE_FONT_CATEGORIES[Number(category)],
        }
      })
  }
  return catalog
}

function loadIndex() {
  if (!byFamily) {
    byFamily = new Map(loadCatalog().map(font => [font.family, font]))
  }
  return byFamily
}

/** Every family, in the order the picker should show them. */
export function getGoogleFonts(): GoogleFont[] {
  return loadCatalog()
}

/** A catalog entry, or undefined for a family this build does not ship. */
export function getGoogleFont(family: string | undefined) {
  if (!family) return undefined
  return loadIndex().get(family)
}

/** Whether a record's family can be rendered by this build. */
export function hasGoogleFont(family: string | undefined) {
  return getGoogleFont(family) !== undefined
}
`

await writeFile(outFile, source)
console.log(`wrote ${rows.length} families to ${outFile}`)
